import { query } from '../../config/database.js';
import { deleteFiles, extractStoragePath, STORAGE_BUCKET } from '../../config/storage.js';
import { UUID_PATTERN } from '../../utils/uuid.js';
import { swallowAndLog } from '../../utils/best-effort.js';
import {
  createStorageManifestRepository,
  type StorageItemRow,
  type StorageManifestDb,
  type StorageScanCursorRow,
} from './storage-manifest.repository.js';

export type DeletionJobKind = 'course' | 'user';

const STORAGE_DELETE_BATCH_SIZE = 100;
const STORAGE_ITEM_LEASE_SECONDS = 10 * 60;
const STORAGE_DISCOVERY_BATCH_SIZE = 500;

const manifestRepository = createStorageManifestRepository({ query } satisfies StorageManifestDb);

/**
 * A course-outline move keeps the physical object key so it does not consume
 * a second copy of the tenant's quota.  A later deletion of the former course
 * must therefore skip objects whose authoritative course_assets row now
 * belongs to another course in the same tenant.
 */
export interface StoragePrefixManifestOptions {
  excludeCourseAssetReferencesForOtherCourses?: string;
}

function isSafeStoragePath(path: string): boolean {
  return path.length <= 1200
    && !path.includes('..')
    && !/[<>"'`\\]/.test(path)
    && !path.startsWith('/')
    && !path.includes('//');
}

/** A cursor must only move forward; replaying an earlier page is safe but skipping one is not. */
export function shouldAdvanceStorageScanCursor(current: string | null, next: string): boolean {
  return current === null || next > current;
}

/**
 * Convert legacy public URLs to object keys and reject paths outside the
 * tenant prefix. A deletion worker must never follow an arbitrary URL.
 */
export function normalizeTenantStoragePath(value: unknown, tenantId: string): string | null {
  if (typeof value !== 'string') return null;
  const raw = value.trim();
  if (!raw) return null;
  const path = extractStoragePath(raw);
  if (!path || !isSafeStoragePath(path)) return null;
  return path.startsWith(`${tenantId}/`) ? path : null;
}

/**
 * Build the only non-directory prefix accepted by the deletion system.
 *
 * Avatars are stored as `{tenant}/avatars/{user}.<extension>`, so a failed
 * profile update can leave one object with no database reference. This keeps
 * recovery exact to that user; callers cannot request a broad avatars scan.
 */
export function getUserAvatarStorageStem(tenantId: string, userId: string): string | null {
  // Any UUID bit pattern (UUID_PATTERN): PostgreSQL accepts every canonical one, not only RFC v4/v7.
  if (!UUID_PATTERN.test(tenantId) || !UUID_PATTERN.test(userId)) return null;
  const stem = `${tenantId}/avatars/${userId}.`;
  return normalizeTenantStoragePath(stem, tenantId) === stem ? stem : null;
}

/**
 * Cursor rows are intentionally constrained to directory-shaped prefixes.
 * This is only a durable cursor identity; storage discovery still uses the
 * exact avatar stem above, never this virtual directory name.
 */
export function getUserAvatarStorageCursorPrefix(tenantId: string, userId: string): string | null {
  const stem = getUserAvatarStorageStem(tenantId, userId);
  if (!stem) return null;
  const cursorPrefix = `${stem}/`;
  return normalizeTenantStoragePath(cursorPrefix, tenantId) === cursorPrefix ? cursorPrefix : null;
}

export async function registerStorageManifestPaths(
  jobKind: DeletionJobKind,
  jobId: string,
  tenantId: string,
  rawPaths: readonly string[],
): Promise<number> {
  const paths = [...new Set(rawPaths
    .map((path) => normalizeTenantStoragePath(path, tenantId))
    .filter((path): path is string => path !== null))];
  if (paths.length === 0) return 0;

  return manifestRepository.insertItems(jobKind, jobId, tenantId, paths);
}

async function getOrCreateStorageScanCursor(
  jobKind: DeletionJobKind,
  jobId: string,
  tenantId: string,
  prefix: string,
): Promise<StorageScanCursorRow> {
  await manifestRepository.ensureScanCursor(jobKind, jobId, tenantId, prefix);
  const cursor = await manifestRepository.selectScanCursor(jobKind, jobId, prefix);
  if (!cursor) throw new Error('Unable to create durable storage scan cursor');
  return cursor;
}

async function advanceStorageScanCursor(
  jobKind: DeletionJobKind,
  jobId: string,
  prefix: string,
  lastStoragePath: string,
): Promise<void> {
  await manifestRepository.advanceScanCursor(jobKind, jobId, prefix, lastStoragePath);
}

async function markStorageScanCursorCompleted(
  jobKind: DeletionJobKind,
  jobId: string,
  prefix: string,
): Promise<void> {
  await manifestRepository.completeScanCursor(jobKind, jobId, prefix);
}

/**
 * Discover objects directly from Supabase's storage catalog before deleting a
 * subject.  DB references alone are not an ownership boundary: an upload may
 * have reached Storage before its application transaction failed.  Prefixes
 * passed here are generated by the server, must stay within one tenant, and
 * are read in a keyset-paginated way so very large courses remain bounded.
 */
async function discoverStoragePrefixManifestPaths(
  jobKind: DeletionJobKind,
  jobId: string,
  tenantId: string,
  scanPrefix: string,
  cursorPrefix = scanPrefix,
  options: StoragePrefixManifestOptions = {},
): Promise<number> {
  const cursor = await getOrCreateStorageScanCursor(jobKind, jobId, tenantId, cursorPrefix);
  if (cursor.completed_at) return 0;

  let after = cursor.last_storage_path || '';
  let registered = 0;
  while (true) {
    const result = await manifestRepository.selectStorageObjectPage({
      bucket: STORAGE_BUCKET,
      scanPrefix,
      after,
      tenantId,
      excludeCourseId: options.excludeCourseAssetReferencesForOtherCourses || null,
      limit: STORAGE_DISCOVERY_BATCH_SIZE,
    });
    if (result.rowCount === 0) {
      await markStorageScanCursorCompleted(jobKind, jobId, cursorPrefix);
      return registered;
    }

    registered += await registerStorageManifestPaths(
      jobKind,
      jobId,
      tenantId,
      result.rows.map((row) => row.storage_path),
    );
    after = result.rows[result.rows.length - 1].storage_path;
    // The manifest insert commits before the cursor advances. A crash can only
    // repeat a page (deduplicated by the manifest key), never skip an object.
    await advanceStorageScanCursor(jobKind, jobId, cursorPrefix, after);
  }
}

/**
 * Discover a server-owned directory prefix before database rows are purged.
 * File-stem discovery is deliberately unavailable here; use the narrow user
 * avatar helper below so no caller can accidentally scan a whole namespace.
 */
export async function registerStoragePrefixManifestPaths(
  jobKind: DeletionJobKind,
  jobId: string,
  tenantId: string,
  prefix: string,
  options: StoragePrefixManifestOptions = {},
): Promise<number> {
  const normalizedPrefix = normalizeTenantStoragePath(prefix, tenantId);
  if (!normalizedPrefix || !normalizedPrefix.endsWith('/')) {
    throw new Error('Unsafe storage prefix blocked deletion discovery');
  }
  return discoverStoragePrefixManifestPaths(jobKind, jobId, tenantId, normalizedPrefix, normalizedPrefix, options);
}

/**
 * Discover only the extension suffixes belonging to one UUID-backed user
 * avatar. The stem is generated here, never accepted from a request or job
 * payload, and remains isolated to exactly one tenant and one user.
 */
export async function registerUserAvatarStemManifestPaths(
  jobId: string,
  tenantId: string,
  userId: string,
): Promise<number> {
  const stem = getUserAvatarStorageStem(tenantId, userId);
  const cursorPrefix = getUserAvatarStorageCursorPrefix(tenantId, userId);
  if (!stem || !cursorPrefix) throw new Error('Unsafe user avatar storage stem blocked deletion discovery');
  return discoverStoragePrefixManifestPaths('user', jobId, tenantId, stem, cursorPrefix);
}

async function claimStorageItems(jobKind: DeletionJobKind, jobId: string): Promise<StorageItemRow[]> {
  return manifestRepository.claimItems(jobKind, jobId, STORAGE_DELETE_BATCH_SIZE, STORAGE_ITEM_LEASE_SECONDS);
}

async function markStorageItemsSucceeded(ids: readonly string[]): Promise<void> {
  if (ids.length === 0) return;
  await manifestRepository.markItemsSucceeded(ids);
}

async function releaseStorageItems(ids: readonly string[], error: unknown): Promise<void> {
  if (ids.length === 0) return;
  const message = error instanceof Error ? error.message : String(error);
  await manifestRepository.releaseItems(ids, message.slice(0, 4000));
}

/**
 * Drain the persistent manifest. The storage call happens before a row is
 * marked succeeded; a process crash merely repeats a safe, idempotent remove.
 */
export async function deleteStorageManifest(jobKind: DeletionJobKind, jobId: string): Promise<number> {
  let deleted = 0;
  while (true) {
    const items = await claimStorageItems(jobKind, jobId);
    if (items.length === 0) return deleted;

    try {
      await deleteFiles(items.map((item) => item.storage_path));
      await markStorageItemsSucceeded(items.map((item) => item.id));
      deleted += items.length;
    } catch (error) {
      await releaseStorageItems(items.map((item) => item.id), error).catch(swallowAndLog('storage_manifest.release'));
      throw error;
    }
  }
}

export async function countUnfinishedStorageManifestItems(jobKind: DeletionJobKind, jobId: string): Promise<number> {
  return Number((await manifestRepository.countUnfinished(jobKind, jobId)) || 0);
}
